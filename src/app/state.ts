/**
 * Состояние приложения.
 *
 * Здесь живёт всё, что не является частью нейронауки: идёт ли симуляция,
 * какая скорость воспроизведения, что выбрано в интерфейсе, какой уровень
 * открыт. Сеть (`Network`) — отдельный объект, и её класс не знает про эти
 * настройки.
 *
 * Хранилище намеренно простое: набор полей и список подписчиков. Цикл
 * симуляции читает поля напрямую (это горячий путь), а интерфейс
 * подписывается на изменения и перерисовывается.
 */

import type { ColorMode } from '../render/palette.js';
import type { NeuronModelKind } from '../core/types.js';

/** Идёт ли симуляция и с какой скоростью. */
export class AppState {
  running = true;

  /**
   * Сколько шагов нейронам выполнять за один кадр отрисовки.
   *
   * При dt = 0.5 мс один шаг — это полмиллисекунды модельного времени,
   * поэтому для «живой» картинки нужно несколько десятков шагов на кадр.
   * Для пространственных сцен шагов нужно меньше: там шаг считается по
   * 2500 нейронам.
   */
  stepsPerFrame = 40;

  /**
   * Подстраивать ли число шагов на кадр автоматически.
   *
   * Нужно для больших сетей: 40 шагов на 2500 нейронов не укладываются в
   * бюджет кадра, и интерфейс начинает подтормаживать. Автоподстройка
   * снижает их, пока кадр не станет дешёвым.
   *
   * ВАЖНО: замер стоимости шага должен считаться ТОЛЬКО по шагам симуляции.
   * В phys-lab этот дефект реально случался (дефект 19): в замер попадала
   * дорогая статистика, и число шагов съезжало к единице на здоровой
   * системе. Здесь замер идёт вокруг `network.run`, и больше нигде.
   */
  autoSteps = true;

  /** Целевая частота кадров. */
  targetFps = 60;

  /** Настройки отрисовки. */
  view: {
    colorMode: ColorMode;
    showLinks: boolean;
    showGrid: boolean;
    neuronScale: number;
    showPulses: boolean;
    /** Радиус «удара током», мировые единицы. */
    brushRadius: number;
    /** Сила «удара током» в единицах LIF. */
    pokeStrength: number;
  } = {
    colorMode: 'potential',
    // Связи выключены по умолчанию: на большой сети их перерисовка дороже
    // симуляции, а картина структуры нужна реже, чем динамика.
    showLinks: false,
    showGrid: true,
    neuronScale: 1,
    // Импульсы включены: это главный ответ на вопрос «куда идёт
    // возбуждение», и без них сцена выглядит статичной картинкой.
    showPulses: true,
    brushRadius: 2.5,
    // Измерено на волне: амплитуда 20 надёжно запускает разряд в пятне
    // радиуса 2.5, а 40 — уже перегружает локальную область. Порог
    // одиночного LIF — 1.5 нА, то есть запас более чем десятикратный.
    pokeStrength: 20,
  };

  /** Активный пресет (для подсветки кнопки). */
  presetId: string | null = 'single-lif';

  /** Открытый уровень кампании или null в режиме песочницы. */
  levelId: string | null = null;

  /** Включён ли STDP. */
  stdpEnabled = true;

  /** Модель нейрона, выбранная вручную. */
  model: NeuronModelKind = 'lif';

  /** Показывать ли осциллограф. */
  showOscilloscope = true;

  /** Показывать ли растровую диаграмму. */
  showRaster = true;

  /**
   * Есть ли на сцене пространственная топология.
   *
   * От этого зависит, показывать ли панель волны и рисовать ли сетку:
   * у случайной сети координаты условные, и сетка там бессмысленна.
   */
  spatial = false;

  /** Список ошибок, собранных на странице — читается смоук-тестом. */
  errors: string[] = [];

  private listeners = new Set<() => void>();

  /** Подписка на изменения. */
  subscribe(listener: () => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  /** Сообщить подписчикам, что состояние изменилось. */
  notify(): void {
    for (const listener of this.listeners) listener();
  }
}

/** Форматирование чисел для подписей интерфейса. */
export const format = {
  /** Величина с разумным числом знаков. */
  value(value: number, digits = 2): string {
    if (!Number.isFinite(value)) return '—';
    const abs = Math.abs(value);
    if (abs >= 10000) return value.toExponential(1);
    if (abs >= 100) return value.toFixed(0);
    return value.toFixed(digits);
  },
  /** Целое с разделителями разрядов. */
  int(value: number): string {
    if (!Number.isFinite(value)) return '—';
    return Math.round(value).toLocaleString('ru-RU');
  },
  /** Время в миллисекундах: до секунды — мс, дальше — с. */
  time(ms: number): string {
    if (!Number.isFinite(ms)) return '—';
    if (ms >= 1000) return `${(ms / 1000).toFixed(2)} с`;
    return `${ms.toFixed(0)} мс`;
  },
  /**
   * Величина, которой может не быть.
   *
   * Отдельная функция, потому что «нет данных» и «ноль» — разные состояния:
   * пока окно статистики не набрано, показывать 0 значило бы врать
   * (инвариант: «нет данных» ≠ «ноль»).
   */
  maybe(value: number, digits = 2): string {
    if (!Number.isFinite(value)) return 'набор…';
    return this.value(value, digits);
  },
};
