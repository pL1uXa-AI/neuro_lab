/** Режим по идентификатору. */
export function modeById(id: string): IzhMode | undefined {
  return IZHI_MODES.find((mode) => mode.id === id);
}

/**
 * Режим в форму, которую понимает ядро: `IzhikevichParams` из `types.ts`.
 *
 * Начальное состояние берётся из ИСТИННОГО состояния покоя при токе в момент
 * t = 0 (`izhRestState`), а не из соглашения «u = b·V». Разница не
 * косметическая: при «u = b·V» система стартует вне равновесия, и каждый
 * прогон открывается паразитным переходным процессом — нейрон успевает
 * «выстрелить» до включения стимула. Именно это ломало rebound-режимы,
 * где спайк появлялся при отрицательном токе (см. историю калибровки
 * каталога в docs/NEXT-SESSION.md).
 */
export function modeToParams(mode: IzhMode): IzhikevichParams {
  const baseline = mode.baseline ?? 0;
  // Точка покоя считается по БАЗОВОМУ току, БЕЗ протокола стимула.
  //
  // Это принципиально, и на этом уже спотыкались: если включить в расчёт
  // стимул (для режимов с постоянным током stimulusCurrent(t=0) равен
  // амплитуде), нейрон стартует УЖЕ приспособленным к стимулу и не
  // заряжается — режим «интегратор» показывал ровную линию, потому что
  // начинался ровно в точке равновесия для приложенного тока.
  //
  // Физически правильно так: нейрон сидит в покое под фоновым током,
  // а протокол стимула затем к нему прикладывается.
  const rest = mode.initial ?? izhRestState(mode.params.b, baseline);
  return {
    a: mode.params.a,
    b: mode.params.b,
    c: mode.params.c,
    d: mode.params.d,
    vPeak: 30,
    vRest: rest.v,
    uRest: rest.u,
  };
}
