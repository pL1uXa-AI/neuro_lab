/**
 * Протокол стимула.
 *
 * Отдельный тип, потому что половина режимов Figure 1 определяется не
 * параметрами, а формой тока: phasic spiking — коротким импульсом,
 * rebound — выключением гиперполяризации, class 1/2 — медленным пандусом.
 */
export type StimulusPattern =
  /** Постоянный ток всё время наблюдения. */
  | { kind: 'const'; amplitude: number; fromMs?: number; toMs?: number }
  /** Короткий прямоугольный импульс. */
  | { kind: 'pulse'; amplitude: number; fromMs: number; toMs: number }
  /** Гиперполяризация, затем её снятие (для rebound-режимов). */
  | { kind: 'release'; amplitude: number; fromMs: number; toMs: number }
  /** Синусоидальный ток: нужен для проверки резонанса. */
  | { kind: 'sine'; amplitude: number; frequencyHz: number; phase?: number }
  /** Линейный пандус тока (для class 1 / class 2). */
  | { kind: 'ramp'; fromAmplitude: number; toAmplitude: number; durationMs: number }
  /** Два импульса заданной длительности с паузой между ними. */
  | {
      kind: 'twoPulses';
      amplitude: number;
      /** Когда начинается первый импульс, мс. */
      firstFromMs: number;
      /** Когда заканчивается первый импульс, мс. */
      firstToMs: number;
      /** Когда начинается второй импульс, мс. */
      secondFromMs: number;
      /** Когда заканчивается второй импульс, мс. */
      secondToMs: number;
    };

/** Ток стимула в момент времени `t` (мс). */
export function stimulusCurrent(pattern: StimulusPattern, t: number): number {
  switch (pattern.kind) {
    case 'const':
      if (t < (pattern.fromMs ?? 0)) return 0;
      if (pattern.toMs !== undefined && t > pattern.toMs) return 0;
      return pattern.amplitude;
    case 'pulse':
      return t >= pattern.fromMs && t < pattern.toMs ? pattern.amplitude : 0;
    case 'release':
      return t >= pattern.fromMs && t < pattern.toMs ? pattern.amplitude : 0;
    case 'sine':
      return (
        pattern.amplitude *
        Math.sin(2 * Math.PI * pattern.frequencyHz * (t / 1000) + (pattern.phase ?? 0))
      );
    case 'ramp': {
      if (t <= 0) return pattern.fromAmplitude;
      if (t >= pattern.durationMs) return pattern.toAmplitude;
      return (
        pattern.fromAmplitude +
        ((pattern.toAmplitude - pattern.fromAmplitude) * t) / pattern.durationMs
      );
    }
    case 'twoPulses': {
      // Границы заданы явно, а не «первый импульс от нуля»: иначе ток
      // включён с самого начала, и нейрон спайкует до первого «импульса».
      // Именно на этом ломалась вариабельность порога.
      const inFirst = t >= pattern.firstFromMs && t < pattern.firstToMs;
      const inSecond = t >= pattern.secondFromMs && t < pattern.secondToMs;
      return inFirst || inSecond ? pattern.amplitude : 0;
    }
  }
}

/**
 * Истинное состояние покоя модели при данном постоянном токе.
 *
 * ─── Почему это обязательно ──────────────────────────────────────────────
 *
 * Распространённое соглашение «u_rest = b·V_rest» верно ТОЛЬКО тогда, когда
 * V_rest действительно является точкой покоя. Если задать произвольное V и
 * положить u = b·V, система оказывается вне равновесия, и каждый прогон
 * начинается со spurious-переходного процесса: нейрон «выстреливает» один-два
 * спайка ещё до включения стимула. Обнаружено при калибровке каталога:
 * режим «пачка оттормаживания» давал спайк на 12-й мс при ОТРИЦАТЕЛЬНОМ токе.
 *
 * Правильное состояние покоя — решение системы
 *
 *     0.04·V² + 5·V + 140 − u + I = 0,   u = b·V
 *     ⇒ 0.04·V² + (5 − b)·V + (140 + I) = 0
 *
 * Берётся УСТОЙЧИВЫЙ корень — меньший из двух: у Izhikevich при типичных b
 * квадратное уравнение имеет два корня, и покою соответствует нижний
 * (у верхнего положительная производная, то есть он отталкивающий).
 *
 * Если корней нет (ток выше порога возбуждения), возвращается состояние
 * на нижней границе ветви: нейрон всё равно не может покоиться, и начинать
 * с бесконечности было бы хуже, чем с разумной оценки.
 */
export function izhRestState(b: number, current = 0): { v: number; u: number } {
  const a2 = 0.04;
  const a1 = 5 - b;
  const a0 = 140 + current;
  const discriminant = a1 * a1 - 4 * a2 * a0;
  if (discriminant < 0) {
    // Корней нет: устойчивая ветвь кончается на вершине параболы.
    const vertex = -a1 / (2 * a2);
    return { v: vertex, u: b * vertex };
  }
  const root = (-a1 - Math.sqrt(discriminant)) / (2 * a2);
  return { v: root, u: b * root };
}

/** Один режим — строка таблицы. */
export interface IzhMode {
  /** Идентификатор для URL, тестов и пресетов. */
  id: string;
  /** Название на русском (интерфейс). */
  title: string;
  /** Латинское сокращение, как в статье (RS, IB, CH, FS, LTS, TC, RZ). */
  shortName?: string;
  /** Что должно быть видно: одна строка для интерфейса. */
  hint: string;
  /** Параметры модели (a, b, c, d). */
  params: { a: number; b: number; c: number; d: number };
  /**
   * Начальное состояние, если «истинного покоя» для режима недостаточно.
   *
   * По умолчанию берётся точка равновесия при токе t = 0. Но часть режимов
   * живёт в области, где равновесия ВООБЩЕ нет (например, бистабильность при
   * b = 1.5: нуль-изоклина V не пересекает нуль-изоклину u). Для них нужен
   * явно заданный тихий старт — тот же, что в `figure1.m` (v = −70, u = −20).
   * Поле существует именно для таких случаев и заполняется осознанно.
   */
  initial?: { v: number; u: number };
  /**
   * Постоянная составляющая тока, мА, поверх протокола стимула.
   *
   * Нужна режимам, которые живут на ненулевом фоне: в `figure1.m` у
   * бистабильности базовый ток равен −65, у режимов от торможения — +80.
   * Без фона нейрон стоит в другом состоянии, и сигнатура не воспроизводится.
   * Точка покоя считается уже С УЧЁТОМ фона (`modeToParams`).
   */
  baseline?: number;
  /**
   * Шаг интегрирования, если режиму нужен свой.
   *
   * По умолчанию 0.1 мс. Но часть режимов (пачки от торможения) при таком
   * шаге неустойчива: член 0.04·V² разгоняет потенциал, и схема «взрывается»
   * (измерено: 1307 спайков и срабатывание ограничителя за 300 мс).
   * В самой статье Izhikevich считал с шагом 0.5 мс, и на нём режим ведёт
   * себя правильно. Это честный компромисс: режим живёт на своём шаге,
   * и это записано здесь, а не спрятано в константе общего шага.
   */
  dt?: number;
  /** Протокол стимула. */
  stimulus: StimulusPattern;
  /** Сколько миллисекунд моделировать. */
  durationMs: number;
  /**
   * Фактический статус воспроизведения — см. заголовок файла.
   * Это не «поле на будущее»: оно заполнено по результатам прогонов.
   */
  verified: 'signature' | 'partial' | 'known-limitation';
  /**
   * Даёт ли режим спайки вообще.
   *
   * Поле нужно потому, что часть режимов — ПОДПОРОГОВЫЕ по определению
   * (интегратор, подпороговые колебания): их сигнатура описывается
   * поведением потенциала, а не спайками. Без этого признака общая
   * проверка «режим что-то делает» требовала бы спайков от всех подряд
   * и была бы неверной.
   */
  spiking: boolean;
  /** Что именно проверяет тест — формулировка сигнатуры. */
  signature: string;
}

