/**
 * Предел шага интегрирования.
 *
 * У Izhikevich член 0.04·V² делает схему явной и потому условно устойчивой:
 * при большом dt потенциал за один шаг уходит в бесконечность. Порог 1.0 мс —
 * это режим самой статьи (там dt = 1 с полушагом), поэтому он разрешён;
 * всё, что больше, — уже не симуляция нейрона, а её пародия.
 */
export const MAX_DT = 1.0;

/**
 * Предел модуля потенциала.
 *
 * Всё, что выше, — признак численного разлёта, а не биологии: спайк — это
 * ≈ +30…+40 мВ, а не +1000. Обнаружив такое, симуляция обязана не
 * «доигрывать» расходящийся сценарий, а восстановить нейрон и сообщить
 * об этом (см. `docs/NEXT-SESSION.md`, инвариант 4).
 */
export const V_INSANE = 500;

/**
 * Состояние всех нейронов.
 *
 * Все массивы одной длины `count`. Индекс нейрона — это его номер; никаких
 * отдельных «объектов нейрона» нет, чтобы горячий цикл не разыменовывал
 * тысячи указателей.
 */
export interface NeuronState {
  /** Число нейронов. */
  count: number;

  /** Мембранный потенциал, мВ. Для LIF — в диапазоне [vReset, vTh]. */
  v: Float64Array;
  /**
   * Переменная восстановления u (только Izhikevich). Для LIF не используется,
   * но массив существует всегда: так состояние сериализуется единообразно,
   * и переключение модели не требует пересборки буферов.
   */
  u: Float64Array;
  /** Остаток рефрактерности, мс. Пока > 0, вход не двигает потенциал. */
  refrac: Float64Array;

  /** Время последнего спайка, мс; -Infinity, если нейрон ещё не спайковал. */
  lastSpike: Float64Array;
  /** Время предпоследнего спайка, мс (нужно для интервала ISI в момент спайка). */
  prevSpike: Float64Array;
  /**
   * Время ПЕРВОГО спайка с начала прогона, мс; -Infinity, если спайков не было.
   *
   * Отдельный массив, а не «первое значение в истории»: измерение волны
   * (`wave.ts`) работает именно по времени первого спайка, потому что волна —
   * это ФРОНТ, и первое возбуждение в каждой точке описывает его движение.
   * Более поздние спайки отражают реверберацию и к фронту отношения не имеют.
   * Восстановить это время из `prevSpike`/`lastSpike` нельзя: они хранят
   * только два последних спайка.
   */
  firstSpike: Float64Array;

  /**
   * Последний интервал между спайками, мс, и его скользящее среднее.
   * Заполняется в момент спайка: кэш для метрик, чтобы не пересчитывать
   * историю спайков на каждом кадре.
   */
  lastIsi: Float64Array;
  meanIsi: Float64Array;
  /** Скользящее среднее квадрата ISI — для CV ISI. */
  meanIsi2: Float64Array;

  /** Число спайков с начала прогона. */
  spikeCount: Uint32Array;
  /** 1, если нейрон спайковал на текущем шаге (для рендера и метрик). */
  spiked: Uint8Array;
  /** 1, если нейрон тормозной. */
  inhibitory: Uint8Array;

  /**
   * Активация для рендера: 1 сразу после спайка, экспоненциально спадает.
   * Отдельный массив, потому что `spiked` живёт ровно один шаг, а «вспышка»
   * на экране должна угасать за несколько десятков миллисекунд.
   */
  flash: Float64Array;

  /** Текущий шаг симуляции. */
  step: number;
  /** Время с начала прогона, мс. */
  time: number;

  /**
   * Сколько раз потенциал вылетал за физические пределы и был восстановлен.
   *
   * Счётчик существует не «на всякий случай»: он делает численный разлёт
   * наблюдаемым. Разлёт не роняет симуляцию и не виден на глаз (нейрон просто
   * перестаёт спайковать), поэтому без счётчика о нём не узнали бы ни
   * пользователь, ни сквозная проверка.
   */
  insane: number;
}

/** Выделение состояния на `count` нейронов. */
export function allocNeuronState(count: number): NeuronState {
  return {
    count,
    v: new Float64Array(count),
    u: new Float64Array(count),
    refrac: new Float64Array(count),
    lastSpike: new Float64Array(count),
    prevSpike: new Float64Array(count),
    firstSpike: new Float64Array(count),
    lastIsi: new Float64Array(count),
    meanIsi: new Float64Array(count),
    meanIsi2: new Float64Array(count),
    spikeCount: new Uint32Array(count),
    spiked: new Uint8Array(count),
    inhibitory: new Uint8Array(count),
    flash: new Float64Array(count),
    step: 0,
    time: 0,
    insane: 0,
  };
}
