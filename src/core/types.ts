/**
 * Модель состояния сети и единицы измерения.
 *
 * ─── Единицы ─────────────────────────────────────────────────────────────
 *
 * Время — миллисекунды (мс), мембранный потенциал — милливольты (мВ).
 * Это нейрофизиологические единицы, а не «приведённые»: у нейронов есть
 * естественные масштабы (τ_m ≈ 20 мс, размах спайка ≈ 100 мВ), и пересчёт
 * в безразмерные величины только запутал бы сверку со статьями.
 *
 * Ток — единственное место, где модели расходятся, и это НЕ ошибка:
 *   • LIF: ток в наноамперах (нА), потому что V_∞ = V_rest + R_in·I,
 *     где R_in в мегаомах даёт мВ. Типичный пороговый ток ≈ 1.5 нА.
 *   • Izhikevich: ток в единицах самого уравнения (`dV/dt = 0.04V² + … + I`),
 *     типичные значения 0…20. Абсолютной физической размерности у него нет.
 * Панель интерфейса обязана показывать единицу рядом с ползунком — иначе
 * пользователь переносит «10» с одной модели на другую и получает или
 * молчание, или спам спайков.
 *
 * ─── Хранение ────────────────────────────────────────────────────────────
 *
 * Все величины нейронов — плоские типизированные массивы (SoA, structure of
 * arrays), а не массив объектов. Горячий цикл обходит десятки тысяч нейронов
 * на каждом шаге; обращение к памяти должно быть последовательным, а сборщик
 * мусора — не участвовать в шаге вовсе.
 */

/** Какая модель описывает динамику нейрона. */
export type NeuronModelKind =
  /** Leaky Integrate-and-Fire: одна переменная, точное решение. */
  | 'lif'
  /** Izhikevich: две переменные, 20+ типов нейронов. */
  | 'izhikevich';

/** Параметры LIF. */
export interface LifParams {
  /** Постоянная времени мембраны τ_m, мс. */
  tauM: number;
  /** Потенциал покоя, мВ. */
  vRest: number;
  /** Порог генерации спайка, мВ. */
  vTh: number;
  /** Потенциал после спайка (сброс), мВ. */
  vReset: number;
  /** Абсолютная рефрактерность, мс. */
  refrac: number;
  /** Входное сопротивление R_in, МОм. */
  rIn: number;
}

/**
 * Параметры Izhikevich.
 *
 * Смысл каждого параметра (Izhikevich, 2003):
 *   a — скорость восстановления (меньше a → медленнее адаптация);
 *   b — чувствительность переменной восстановления к подпороговому V;
 *   c — потенциал после спайка, мВ; при c = V_th нейрон не «сбрасывается»;
 *   d — приращение восстановления после спайка (сила адаптации).
 *
 * Конкретные наборы (RS, IB, CH, FS, LTS, …) лежат в `neuron-types.ts`
 * как данные, а не как код.
 */
export interface IzhikevichParams {
  a: number;
  b: number;
  c: number;
  d: number;
  /** Порог, при котором регистрируется спайк и применяется сброс, мВ. */
  vPeak: number;
  /** Начальный потенциал покоя для этой конфигурации, мВ. */
  vRest: number;
  /** Начальное значение переменной восстановления u. */
  uRest: number;
}

/** Полный набор параметров нейрона: общие + параметры конкретной модели. */
export interface NeuronParams {
  model: NeuronModelKind;
  lif: LifParams;
  izh: IzhikevichParams;
}

/**
 * Параметры LIF по умолчанию — «типичная пирамидная клетка в срезе».
 *
 * Пороговый ток при этих значениях равен (vTh − vRest)/rIn = 1.5 нА: это
 * ровно тот ток, при котором нейрон начинает выдавать спайки, и по нему
 * удобно проверять f–I кривую (частота начинается с нуля).
 */
export const DEFAULT_LIF: LifParams = {
  tauM: 20,
  vRest: -65,
  vTh: -50,
  vReset: -70,
  refrac: 2,
  rIn: 10,
};

/**
 * Параметры Izhikevich по умолчанию — «regular spiking» (RS).
 *
 * ─── О `vRest` и `uRest` ─────────────────────────────────────────────────
 *
 * Это НЕ произвольные числа: они обязаны быть точкой покоя для данных
 * `(a, b, c, d)`. Для `b = 0.2` и нулевого тока решение системы
 * `0.04·V² + (5 − b)·V + 140 = 0, u = b·V` даёт **V = −70, u = −14**
 * (см. `izhRestState` в `neuron-types.ts`).
 *
 * Распространённое значение «v = −65» — это НЕ покой, а просто характерный
 * потенциал из примеров статьи. При `v = −65, u = b·v = −13` производная
 * `dV/dt = 169 − 325 + 140 + 13 = −3 мВ/мс`, то есть нейрон с самого начала
 * уезжает вниз и через десятки миллисекунд ведёт себя не так, как ожидается.
 * Именно этот дефект был найден при первых прогонах сети.
 */
export const DEFAULT_IZH: IzhikevichParams = {
  a: 0.02,
  b: 0.2,
  c: -65,
  d: 8,
  vPeak: 30,
  vRest: -70,
  uRest: -14,
};

/** Параметры по умолчанию целиком. */
export const DEFAULT_NEURON_PARAMS: NeuronParams = {
  model: 'lif',
  lif: DEFAULT_LIF,
  izh: DEFAULT_IZH,
};

/** Тип нейрона по знаку его синапсов. */
export type NeuronType =
  /** Возбуждающий: увеличивает потенциал цели. */
  | 'excitatory'
  /** Тормозной: снижает потенциал цели. */
  | 'inhibitory';

/**
 * Тип входного воздействия на нейрон.
 *
 * Он есть потому, что от него зависит ВСЯ наука в проекте: пуассоновский
 * вход даёт нерегулярный режим (CV ISI ≈ 1), постоянный ток — регулярный
 * (CV ≈ 0), а пространственный стимул — волну. Без явного различия этих
 * режимов «сеть шумит» невозможно ни измерить, ни повторить.
 */
export type InputMode =
  /** Постоянный ток на все нейроны. */
  | 'const'
  /** Пуассоновский поток синаптических событий. */
  | 'poisson'
  /** Ничего: только связи и то, что накликал пользователь. */
  | 'none';

/** Параметры внешнего входа. */
export interface InputParams {
  mode: InputMode;
  /** Амплитуда: нА для LIF, единицы уравнения для Izhikevich. */
  amplitude: number;
  /** Частота пуассоновских событий на нейрон, Гц. */
  rate: number;
  /** Амплитуда одного пуассоновского события (то же, что амплитуда). */
  weight: number;
  /** Доля нейронов, получающих внешний вход (0…1). */
  fraction: number;
}

/** Внешний вход по умолчанию: слабый пуассоновский фон. */
export const DEFAULT_INPUT: InputParams = {
  mode: 'const',
  amplitude: 1.6,
  rate: 100,
  weight: 0.6,
  fraction: 1,
};

/** Параметры мира, которые меняет интерфейс. */
export interface NetworkParams {
  /** Число нейронов. */
  count: number;
  /** Доля тормозных нейронов (0…1). Обычно 0.2 — как в коре. */
  inhibitoryFraction: number;
  /** Шаг интегрирования, мс. */
  dt: number;
  /** Параметры нейрона. */
  neuron: NeuronParams;
  /** Внешний вход. */
  input: InputParams;
  /** Скорость проведения: базовое время доставки спайка, мс. */
  delay: number;
  /** Разброс задержек (доля от базовой), 0 — все связи одинаковы. */
  delayJitter: number;
  /** Зерно генератора: определяет и топологию, и шум. */
  seed: number;
  /** Моделировать ли рефрактерность (для тестов «без неё»). */
  useRefractory: boolean;
  /**
   * Постоянная времени синаптического тока τ_syn, мс.
   *
   * ─── Почему это обязательно ─────────────────────────────────────────────
   *
   * Первая версия прибавляла вес спайка к току ровно на ОДИН шаг. При
   * dt = 0.5 мс это давало скачок потенциала всего ≈0.25·w мВ, и рекуррентное
   * возбуждение не могло поддержать активность: спайки 60 входов приходили
   * в разные моменты и не суммировались. Измерено: активность гасла за
   * 100–300 мс при ЛЮБОЙ силе связи, то есть рабочей памяти не возникало.
   *
   * С затухающим током (стандартная модель «экспоненциальный синапс»)
   * вклады разных спайков складываются за время τ_syn, и рекуррентная сеть
   * начинает поддерживать активность — как в коре, где ВПСТ длятся
   * единицы миллисекунд, а не один шаг интегрирования.
   *
   * τ_syn = 5 мс — типичное значение для AMPA-синапсов возбуждающих клеток.
   */
  synapticTau: number;
  /**
   * Во сколько раз тормозной вес больше возбуждающего по модулю.
   *
   * Нужен сети «на живу», а не только при сборке топологии. Правка доли
   * торможения меняет ЗНАК весов, и чтобы вернуть связь обратно (или сделать
   * тормозной ту, что была возбуждающей), надо знать исходное соотношение.
   * При зашитой константе правка ползунка умножала бы уже умноженное:
   * измерено — отношение 5 превращалось в 20 при одном касании ползунка.
   */
  inhibitoryRatio: number;
}

