/**
 * Кампания: уровни как данные.
 *
 * Идея взята из phys-lab и logic-lab: уровень — это ЗАПИСЬ, а не код.
 * Условие проверки описывается декларативно (`LevelCheck`), а вычисляет его
 * отдельный модуль (`checks.ts`), знающий про нейронауку.
 *
 * ─── Почему условия именно такие ─────────────────────────────────────────
 *
 * «Посмотри, как нейрон адаптируется» проверить нельзя, а «средний ISI во
 * второй половине больше, чем в первой, в 1.5 раза» — можно, и это ровно та
 * величина, по которой нейрофизиолог судит об адаптации. Каждое условие
 * снабжено подсказкой: если игрок не проходит проверку, он видит, ЧТО
 * именно не выполнено, а не «неправильно».
 *
 * Пороги взяты из ИЗМЕРЕНИЙ (замеры в docs/NEXT-SESSION.md и в тестах), а не
 * назначены произвольно. Если правишь параметры сцены — прогони уровень и
 * убедись, что он всё ещё проходится: тест «каждый уровень проходится»
 * существует именно для этого.
 */

import type { ColorMode } from '../render/palette.js';

/** Что проверяет условие уровня. */
export type LevelCheck =
  /** Частота спайков в окне, Гц. */
  | { kind: 'rate'; min?: number; max?: number; label: string }
  /** Число спайков у выбранного нейрона. */
  | { kind: 'spikeCount'; neuron: number; min?: number; max?: number; label: string }
  /** Число нейронов, спайковавших хотя бы раз. */
  | { kind: 'activeNeurons'; min?: number; max?: number; label: string }
  /** Коэффициент вариации ISI: регулярность разряда. */
  | { kind: 'cv'; min?: number; max?: number; label: string }
  /** Наличие групп спайков (пачек). */
  | { kind: 'bursts'; neuron: number; min?: number; label: string }
  /** Тренд ISI: во сколько раз хвост длиннее начала (адаптация). */
  | { kind: 'isiTrend'; neuron: number; min?: number; label: string }
  /** Синхронность популяции 0…1. */
  | { kind: 'synchrony'; min?: number; max?: number; label: string }
  /** Разброс весов: максимальный минус минимальный среди возбуждающих. */
  | { kind: 'weightSpread'; min?: number; label: string }
  /** Сколько раз обновлялись веса (работало ли STDP). */
  | { kind: 'stdpUpdates'; min?: number; label: string }
  /** Насколько далеко ушла волна от центра, клеток. */
  | { kind: 'waveReach'; min?: number; label: string }
  /** Качество линейности фронта (R²). */
  | { kind: 'waveFit'; min?: number; label: string }
  /** Длительность удержания активности после стимула, мс. */
  | { kind: 'memoryHold'; min?: number; label: string }
  /** Прирост спайков после снятия стимула. */
  | { kind: 'memoryGrowth'; min?: number; label: string };

/** Уровень кампании. */
export interface Level {
  /** Идентификатор вида «level-01». */
  id: string;
  title: string;
  /** Что нужно сделать (одна строка). */
  goal: string;
  /** Краткая теория: 2–4 абзаца markdown. */
  theory: string;
  /** Подсказки, если не получается. */
  hints: string[];
  /** Пресет, с которого начинается уровень. */
  presetId: string;
  /** Режим раскраски, подходящий для этого уровня. */
  colorMode?: ColorMode;
  /** Сколько миллисекунд модельного времени набрать перед проверкой. */
  observeMs: number;
  /** Условия, которые обязаны выполниться все. */
  checks: LevelCheck[];
  /** Что показывать поверх сцены. */
  task: string;
}

